#include "Renderer/ShaderCompiler.h"

#include <cstddef>
#include <cstdint>
#include <expected>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <ios>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

void writeCode(std::ostringstream& body, const std::string& name, const std::vector<uint32_t>& code) {
    body << "inline constexpr uint32_t " << name << "[] = {";

    std::ios_base::fmtflags originalFlags = body.flags();

    for (size_t i = 0; i < code.size(); i++) {
        if (i > 0) {
            body << ", ";
        }
        body << "0x" << std::hex << std::setfill('0') << std::setw(8) << code[i];
    }

    body << "};\n";
    body.flags(originalFlags);
}

void writeHeader(std::filesystem::path outputFile, const std::string& body, const std::vector<std::string>& names) {
    std::ofstream out(outputFile);
    if (!out.is_open()) {
        std::cerr << "[SHADERBAKER][ERROR]: Could not open " << outputFile << "for writing\n";
        return;
    }

    out << "// AUTO-GENERATED BY AXIOM SHADER BAKER. DO NOT EDIT\n"
        << "#pragma once\n"
        << "#include <cstdint>\n"
        << "#include <string_view>\n"
        << "namespace Axiom::BuiltInShaders {\n\n";

    out << body << "\n";

    out << "struct Entry {\n"
        << "    std::string_view name;\n"
        << "    std::span<const uint32_t> vertex;\n"
        << "    std::span<const uint32_t> fragment;\n"
        << "};\n\n";

    out << "inline constexpr Entry Table[] = {\n";
    for (const std::string& name : names) {
        out << "    {\"" << name << "\", " << name << "VertexSPIRV, " << name << "FragmentSPIRV},\n";
    }
    out << "};\n\n";
    out << "} // namespace Axiom::BuiltInShaders\n";
    out.close();
}

int main(int argc, char** argv) {
    if (argc < 3) {
        std::cerr << "Usage: AxiomShaderBaker <InputDir> <OutputFile>\n";
        return 1;
    }

    std::filesystem::path inputDir = argv[1];
    std::filesystem::path outputFile = argv[2];
    Axiom::ShaderCompiler compiler(inputDir / "Includes");
    std::vector<std::string> names;
    std::ostringstream body;

    for (const auto& entry : std::filesystem::directory_iterator(inputDir)) {
        std::string file = entry.path().filename().string();
        if (entry.path().extension() != ".axs" || !file.starts_with("BuiltIn.")) {
            continue;
        }

        std::string name = entry.path().stem().string().substr(8); // skips the 'BuiltIn.'

        std::ifstream in(entry.path(), std::ios::in | std::ios::binary | std::ios::ate);
        if (!in.is_open()) {
            std::cerr << "[SHADERBAKER][ERROR]: Could not open " << entry.path() << "for reading\n";
            return 1;
        }
        const size_t size = in.tellg();
        std::string buffer(size, '\0');
        in.seekg(0, std::ios::beg);
        in.read(buffer.data(), size);
        in.close();

        auto sources = Axiom::ShaderCompiler::split(buffer);
        auto compiled = sources ? compiler.compile(sources.value(), name) : std::unexpected<std::string>(sources.error());
        if (!compiled) {
            std::cerr << "[SHADERBAKER]: " << name << ": " << compiled.error() << "\n";
            return 1;
        }

        writeCode(body, name + "VertexSPIRV", compiled->vertex);
        writeCode(body, name + "FragmentSPIRV", compiled->fragment);
        names.push_back(name);
    }
    writeHeader(outputFile, body.str(), names);
}
